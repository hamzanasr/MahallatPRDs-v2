def settings_section(num):
    S = D['settings']
    used = set()
    parts = []
    groups = [(g, list(idx)) for g, idx in SETTING_GROUPS]
    refs = dict(SETTING_REFS)
    for i, g, r in SETTING_REFS_ADD:
        next(x for x in groups if x[0] == g)[1].append(i)
        refs[i] = r
    for gname, idx in groups:
        rows = []
        for i in idx:
            a, b, c = S[i]
            used.add(i)
            rows.append(['<b>%s</b>' % esc(a), lines(b), lines(c), refs_html(refs[i])])
        parts.append('<h3>%s</h3>%s' % (gname, tbl(['الإعداد', 'القيمة الافتراضية', 'الحدود والأثر', 'المتطلب'], rows, 'tbl-set')))
    assert used == set(range(len(S))), set(range(len(S))) - used
    return ('<section id="settings"><h2><span class="num">%d</span>القيم المرنة</h2>'
            '<p class="sub">%d إعداداً يضبطها المسؤول المخوّل من لوحة الإدارة دون إصدار جديد. كل قيمة إعداد عام للنظام، ويمكن تعديل ما يخص التشغيل والرسوم لكل مدينة. القيم المكتوبة هنا افتراضية عند الإطلاق، ويحفظ الطلب نسخة ما استخدمه منها عند تأكيده ( <a class="rid" href="#ADM-034">ADM-034</a> ). ما يخص الاتفاق التجاري يُحفظ في عقد التاجر.</p>%s</section>') % (num, len(S), ''.join(parts))


