def reports_section(num):
    parts = []
    for owner, rows in D['reports'].items():
        groups = []
        for r in rows:
            if r['group'] not in groups:
                groups.append(r['group'])
        body = ''
        for g in groups:
            rs = [r for r in rows if r['group'] == g]
            body += '<h4>%s <small>%d</small></h4>%s' % (esc(g), len(rs), tbl(['التقرير', 'ما يعرضه'], [['<b>%s</b>' % esc(r['title']), fmt(r['description'])] for r in rs]))
        parts.append('<details class="rep" id="rep-%s"><summary><b>%s</b> <span class="cnt">%d تقريراً</span></summary>%s</details>' % (
            'merchant' if 'التاجر' in owner else 'admin', esc(owner), len(rows), body))
    return ('<section id="reports"><h2><span class="num">%d</span>التقارير</h2>'
            '<p class="sub">تقارير التاجر والإدارة تشترك في تعريفات المؤشرات وتراعي الدور والفرع والمدينة. كل تقرير يدعم الفترة المخصصة والمقارنة والتصدير إلى Excel وPDF والإرسال المجدول بالبريد ( <a class="rid" href="#REP-001">REP-001</a> · <a class="rid" href="#MER-035">MER-035</a> · <a class="rid" href="#ADM-006">ADM-006</a> ). لا تتضمن تقارير التاجر جوالات العملاء ولا عناوينهم.</p>%s</section>') % (num, ''.join(parts))
