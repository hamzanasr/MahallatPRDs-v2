def req_html(r, fixes):
    rules = fixes.get(r['id'], {}).get('rules', r['rules'])
    acc = fixes.get(r['id'], {}).get('acceptance', r['acceptance'])
    k, label = PRI[r['priority']]
    used = USED.get(r['id'], [])
    used_html = ''
    if used:
        used_html = '<div class="used"><h5>الصفحات التي تستعمله</h5><p>%s</p></div>' % ' · '.join('<a href="#p-%s">%s %s</a>' % (i, i, esc(PAGES[i]['title'])) for i in used)
    return ('<details class="req" data-p="%s" id="%s"><summary><bdi class="rid">%s</bdi> <span class="rt">%s</span> <span class="tag %s">%s</span></summary>'
            '<div class="rbody"><div><h5>القواعد</h5><ul>%s</ul></div><div><h5>معيار القبول</h5><ul>%s</ul></div>%s</div></details>') % (
        k, r['id'], r['id'], esc(r['title']), k, label, ''.join('<li>%s</li>' % fmt(x) for x in rules), ''.join('<li>%s</li>' % fmt(x) for x in acc), used_html)


