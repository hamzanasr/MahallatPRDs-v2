def _cell(c):
    if isinstance(c, list):
        return refs_html(c)
    return fmt(c)


def blocks_html(blocks):
    out = []
    for b in blocks:
        k = b[0]
        if k == 'h3':
            out.append('<h3>%s</h3>' % esc(b[1]))
        elif k == 'p':
            out.append('<p>%s</p>' % fmt(b[1]))
        elif k == 'note':
            out.append('<div class="note">%s</div>' % fmt(b[1]))
        elif k in ('ol', 'ul'):
            cls = ' class="steps"' if k == 'ol' else ''
            inner = ''.join(('<li><div>%s</div></li>' if k == 'ol' else '<li>%s</li>') % fmt(x) for x in b[1])
            out.append('<%s%s>%s</%s>' % (k, cls, inner, k))
        elif k == 'table':
            out.append(tbl([esc(h) for h in b[1]], [[_cell(c) for c in r] for r in b[2]]))
    return ''.join(out)


def blocks_md(blocks):
    L = []
    for b in blocks:
        k = b[0]
        if k == 'h3':
            L += ['### ' + b[1], '']
        elif k in ('p', 'note'):
            L += [('> ' if k == 'note' else '') + b[1], '']
        elif k in ('ol', 'ul'):
            L += [('%d. ' % (i + 1) if k == 'ol' else '- ') + x for i, x in enumerate(b[1])] + ['']
        elif k == 'table':
            L.append('| ' + ' | '.join(b[1]) + ' |')
            L.append('|' + '---|' * len(b[1]))
            for r in b[2]:
                L.append('| ' + ' | '.join(' '.join(c) if isinstance(c, list) else c for c in r) + ' |')
            L.append('')
    return L


